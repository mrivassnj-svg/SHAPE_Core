from __future__ import annotations

import os
import sys
from pathlib import Path

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

# Adjust this to the absolute path of the SHAPE_Core repo root
REPO_ROOT = Path(__file__).resolve().parent.parent
ASSETS_DIR = REPO_ROOT / "demo" / "assets"
OUTPUT_DIR = REPO_ROOT / "demo" / "output"
OUTPUT_FILE = OUTPUT_DIR / "FN_Demo_MichaelRivas_Group3_ITAI2376_14562.mp4"

FPS = 30
RESOLUTION_X = 1920
RESOLUTION_Y = 1080

# ---------------------------------------------------------------------------
# Clip manifest
# Each entry: (clip_id, start_sec, end_sec, asset_filename, channel)
# channel 1 = video, channel 2 = audio (voice), channel 3 = music
# ---------------------------------------------------------------------------
CLIP_MANIFEST = [
    # (clip_id,          start_s, end_s,  video_asset,              voice_asset)
    ("CLIP_CREDITS",        0,     12,  "title_card.png",           "voice_CLIP_CREDITS.wav"),
    ("CLIP_INTRO",         12,     60,  "screen_capture_nb1.mp4",   "voice_CLIP_INTRO.wav"),
    ("CLIP_WHY",           60,    115,  "screen_capture_nb2.mp4",   "voice_CLIP_WHY.wav"),
    ("CLIP_DEVICE",       115,    150,  "pi_photo.jpg",             "voice_CLIP_DEVICE.wav"),
    ("CLIP_LIVE_DEMO",    150,    210,  "screen_capture_nb3.mp4",   "voice_CLIP_LIVE_DEMO.wav"),
    ("CLIP_CODE",         210,    250,  "screen_capture_nb4.mp4",   "voice_CLIP_CODE.wav"),
    ("CLIP_PITCH",        250,    290,  "montage.mp4",              "voice_CLIP_PITCH.wav"),
    ("CLIP_END",          290,    300,  "end_card.png",             "voice_CLIP_END.wav"),
]

TOTAL_DURATION_S = 300  # 5 minutes


# ---------------------------------------------------------------------------
# Blender VSE assembly
# ---------------------------------------------------------------------------

def build_vse() -> None:
    """Main function: build the VSE sequence and configure render settings."""
    try:
        import bpy  # only available inside Blender
    except ImportError:
        print("[render_demo] ERROR: This script must be run inside Blender.")
        print("  blender --background --python demo/render_demo.py")
        sys.exit(1)

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    scene = bpy.context.scene
    _configure_render(scene)
    _configure_scene(scene)

    # Ensure we have a VSE sequence editor
    if not scene.sequence_editor:
        scene.sequence_editor_create()
    seq = scene.sequence_editor

    # Clear any existing strips
    for strip in list(seq.sequences_all):
        seq.sequences.remove(strip)

    # Add all clips
    for clip_id, start_s, end_s, video_asset, voice_asset in CLIP_MANIFEST:
        _add_video_strip(seq, clip_id, start_s, end_s, video_asset)
        _add_voice_strip(seq, clip_id, start_s, end_s, voice_asset)

    # Add background music across the full video (channel 4, low volume)
    _add_music_strip(seq)

    # Add fade-in / fade-out transitions
    _add_crossfades(seq)

    print(f"\n[render_demo] VSE assembled. {len(CLIP_MANIFEST)} clips.")
    print(f"[render_demo] Output: {OUTPUT_FILE}")
    print("[render_demo] Starting render...\n")

    bpy.ops.render.render(animation=True)
    print(f"\n[render_demo] ✅ Done. Video saved to:\n  {OUTPUT_FILE}")


# ---------------------------------------------------------------------------
# Render settings
# ---------------------------------------------------------------------------

def _configure_render(scene) -> None:
    import bpy
    rd = scene.render
    rd.resolution_x = RESOLUTION_X
    rd.resolution_y = RESOLUTION_Y
    rd.resolution_percentage = 100
    rd.fps = FPS
    rd.image_settings.file_format = "FFMPEG"
    rd.ffmpeg.format = "MPEG4"
    rd.ffmpeg.codec = "H264"
    rd.ffmpeg.constant_rate_factor = "MEDIUM"  # quality vs file size balance
    rd.ffmpeg.audio_codec = "AAC"
    rd.ffmpeg.audio_bitrate = 192
    rd.filepath = str(OUTPUT_FILE)


def _configure_scene(scene) -> None:
    scene.frame_start = 1
    scene.frame_end = TOTAL_DURATION_S * FPS  # 9000 frames @ 30fps


# ---------------------------------------------------------------------------
# Strip helpers
# ---------------------------------------------------------------------------

def _frame(seconds: float) -> int:
    """Convert seconds to Blender frame number (1-indexed)."""
    return int(seconds * FPS) + 1


def _add_video_strip(seq, clip_id: str, start_s: int, end_s: int, asset: str) -> None:
    """Add one video or image strip to channel 1."""
    import bpy

    asset_path = ASSETS_DIR / asset
    if not asset_path.exists():
        print(f"  [WARN] Asset not found, skipping: {asset_path}")
        _add_color_placeholder(seq, clip_id, start_s, end_s)
        return

    start_frame = _frame(start_s)
    end_frame = _frame(end_s)
    duration = end_frame - start_frame

    ext = asset_path.suffix.lower()
    if ext in (".mp4", ".mov", ".avi", ".mkv"):
        strip = seq.sequences.new_movie(
            name=clip_id,
            filepath=str(asset_path),
            channel=1,
            frame_start=start_frame,
        )
        # Trim or extend to fit the target window
        strip.frame_final_end = end_frame
    else:
        # Still image — treat as image strip with the right duration
        strip = seq.sequences.new_image(
            name=clip_id,
            filepath=str(asset_path),
            channel=1,
            frame_start=start_frame,
        )
        strip.frame_final_duration = duration

    print(f"  [VIDEO] {clip_id:<20} frames {start_frame:>5}–{end_frame:>5}  ({asset})")


def _add_color_placeholder(seq, clip_id: str, start_s: int, end_s: int) -> None:
    """Add a dark blue color strip when an asset is missing (graceful fallback)."""
    start_frame = _frame(start_s)
    duration = _frame(end_s) - start_frame
    strip = seq.sequences.new_effect(
        name=f"{clip_id}_placeholder",
        type="COLOR",
        channel=1,
        frame_start=start_frame,
        frame_end=start_frame + duration,
    )
    strip.color = (0.05, 0.08, 0.20)  # dark navy blue
    print(f"  [COLOR] {clip_id:<20} placeholder (asset missing)")


def _add_voice_strip(seq, clip_id: str, start_s: int, end_s: int, voice_asset: str) -> None:
    """Add narration audio strip to channel 2, locked to clip start."""
    import bpy

    asset_path = ASSETS_DIR / voice_asset
    if not asset_path.exists():
        print(f"  [WARN] Voice asset not found, skipping: {asset_path}")
        return

    start_frame = _frame(start_s)
    end_frame = _frame(end_s)

    strip = seq.sequences.new_sound(
        name=f"voice_{clip_id}",
        filepath=str(asset_path),
        channel=2,
        frame_start=start_frame,
    )
    strip.frame_final_end = end_frame
    strip.volume = 1.0
    print(f"  [VOICE] {clip_id:<20} frames {start_frame:>5}–{end_frame:>5}  ({voice_asset})")


def _add_music_strip(seq) -> None:
    """Add background music on channel 3 at low volume."""
    import bpy

    music_path = ASSETS_DIR / "bg_music.mp3"
    if not music_path.exists():
        print(f"  [WARN] bg_music.mp3 not found, skipping background music.")
        return

    strip = seq.sequences.new_sound(
        name="bg_music",
        filepath=str(music_path),
        channel=3,
        frame_start=1,
    )
    strip.frame_final_end = _frame(TOTAL_DURATION_S)
    strip.volume = 0.12  # quiet under narration

    # Fade out in the last 5 seconds
    strip.keyframe_insert("volume", frame=_frame(TOTAL_DURATION_S - 5))
    strip.volume = 0.0
    strip.keyframe_insert("volume", frame=_frame(TOTAL_DURATION_S))

    print(f"  [MUSIC] bg_music — full video, vol=0.12, fade out at {TOTAL_DURATION_S - 5}s")


def _add_crossfades(seq) -> None:
    """
    Add a 1-second cross-fade transition between every adjacent clip pair.
    """
    import bpy

    strips_ch1 = sorted(
        [s for s in seq.sequences_all if s.channel == 1],
        key=lambda s: s.frame_final_start,
    )
    for i in range(len(strips_ch1) - 1):
        a = strips_ch1[i]
        b = strips_ch1[i + 1]
        overlap_frames = FPS  # 1 second

        # Push strip B back slightly to create overlap for the transition
        b.frame_start -= overlap_frames

        try:
            seq.sequences.new_effect(
                name=f"fade_{i}",
                type="GAMMA_CROSS",
                channel=5,
                frame_start=b.frame_final_start,
                frame_end=b.frame_final_start + overlap_frames,
                seq1=a,
                seq2=b,
            )
            print(f"  [FADE] Crossfade between clip {i} and {i + 1}")
        except Exception as exc:  # noqa: BLE001
            print(f"  [WARN] Could not add crossfade {i}→{i+1}: {exc}")


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

if __name__ == "__main__":
    build_vse()
